declare(strict_types=1);

namespace Bedriox\Api\Visibility;

enum VisibilityMode
{
    /** Follow ordinary world, dimension, chunk and tracking-distance admission. */
    case AUTOMATIC;

    /** Admit only explicitly selected authenticated player UUIDs. */
    case SELECTED;

    /** Follow automatic admission except for explicitly excluded player UUIDs. */
    case EXCLUDED;

    /** Admit nobody. */
    case HIDDEN;
}
