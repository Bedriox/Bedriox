declare(strict_types=1);

namespace Bedriox\Api\Entity\Value;

use InvalidArgumentException;

/** Validated Bedrock emote UUID. */
final readonly class EmoteId
{
    public string $value;

    public function __construct(string $value)
    {
        $normalized = strtolower($value);
        if (preg_match('/^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/D', $normalized) !== 1) {
            throw new InvalidArgumentException('Emote ID must be a canonical UUID.');
        }
        $this->value = $normalized;
    }

    public function __toString(): string
    {
        return $this->value;
    }
}
