declare(strict_types=1);

namespace Bedriox\Server\Command\Default;

final class CommandDisplayName
{
    public static function identifier(string $identifier): string
    {
        if (!str_starts_with($identifier, 'minecraft:')) {
            return $identifier;
        }
        $display = substr($identifier, strlen('minecraft:'));

        return ucwords(str_replace(['_', '-'], ' ', $display));
    }

    private function __construct() {}
}
