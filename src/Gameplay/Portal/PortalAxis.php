declare(strict_types=1);

namespace Bedriox\Server\Gameplay\Portal;

enum PortalAxis: string
{
    case X = 'x';
    case Z = 'z';

    public function stepX(): int
    {
        return $this === self::X ? 1 : 0;
    }

    public function stepZ(): int
    {
        return $this === self::Z ? 1 : 0;
    }
}
