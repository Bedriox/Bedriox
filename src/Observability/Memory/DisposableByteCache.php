declare(strict_types=1);

namespace Bedriox\Server\Observability\Memory;

/** Rebuildable byte cache which can release its least-recently-used entries. */
interface DisposableByteCache
{
    public function retainedBytes(): int;

    /** Reduces retained bytes to at most the target and returns the released byte count. */
    public function trimToBytes(int $targetBytes): int;
}
